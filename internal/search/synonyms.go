// tokens делит текст на слова в нижнем регистре; ё → е. Точка, дефис и косая черта внутри слова
// сохраняются («пр-т», «ж/д», «ул.»), запятые и прочие знаки — разделители.
func tokens(s string) []string {
	s = strings.ReplaceAll(strings.ToLower(s), "ё", "е")
	return strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '.' && r != '-' && r != '/' && r != '²'
	})
}

// expandAbbreviations заменяет сокращения полными формами.
func expandAbbreviations(words []string) []string {
	out := make([]string, len(words))
	for i, w := range words {
		if full, ok := abbreviations[w]; ok {
			out[i] = full
		} else {
			out[i] = strings.TrimRight(w, ".")
		}
	}
	return out
}

// alternatives — для фразы запроса (уже без сокращений) её синонимы, если фраза входит в группу.
func alternatives(phrase string) []string {
	for _, g := range synonymGroups {
		for _, v := range g {
			if v == phrase {
				return g
			}
		}
	}
	return nil
}

// Term — часть запроса: фраза и её равнозначные формы (первая — как в запросе).
type Term struct {
	Forms []string
}

// terms группирует слова запроса: самые длинные фразы из словаря синонимов — одним термином,
// остальные слова — по одному.
func terms(words []string) []Term {
	var out []Term
	for i := 0; i < len(words); {
		matched := 0
		var forms []string
		for n := min(5, len(words)-i); n >= 1; n-- {
			if alt := alternatives(strings.Join(words[i:i+n], " ")); alt != nil {
				matched, forms = n, alt
				break
			}
		}
		if matched == 0 {
			out = append(out, Term{Forms: []string{words[i]}})
			i++
			continue
		}
		phrase := strings.Join(words[i:i+matched], " ")
		ordered := []string{phrase}
		for _, f := range forms {
			if f != phrase {
				ordered = append(ordered, f)
			}
		}
		out = append(out, Term{Forms: ordered})
		i += matched
	}
	return out
}
