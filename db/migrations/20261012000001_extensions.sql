-- Нормализация текста для поиска: нижний регистр, ё → е, без диакритики.
-- +goose StatementBegin
CREATE FUNCTION core.normalize_text(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$
    SELECT lower(translate(public.unaccent('public.unaccent'::regdictionary, t), 'ёЁ', 'еЕ'))
$$;
-- +goose StatementEnd

